`timescale 1ns / 1ps

module ALU_tb;

reg clk;
reg reset;

reg [7:0] A;
reg [7:0] B;

reg [2:0] OP;

wire [7:0] RESULT;
wire CARRY;


// ========================================
// ALU Instance
// ========================================

ALU DUT(
    .clk(clk),
    .reset(reset),
    .A(A),
    .B(B),
    .OP(OP),
    .RESULT(RESULT),
    .CARRY(CARRY)
);

// ========================================
// Clock
// ========================================

initial begin

    clk = 0;

    forever #5 clk = ~clk;

end


// ========================================
// Test Cases
// ========================================

initial begin


    // ------------------------------------
    // RESET
    // ------------------------------------

    reset = 1;

    A = 8'b00000000;
    B = 8'b00000000;
    OP = 3'b000;

    #10;

    reset = 0;
	 
    // ------------------------------------
    // 1. ADDITION
    // A + B
    // 10 + 5 = 15
    // ------------------------------------

    A = 8'd10;
    B = 8'd5;
    OP = 3'b000;

    #10;


    // ------------------------------------
    // 2. SUBTRACTION
    // A - B
    // 10 - 5 = 5
    // ------------------------------------

    A = 8'd10;
    B = 8'd5;
    OP = 3'b001;

    #10;
	     // ------------------------------------
    // 3. XOR
    // ------------------------------------

    A = 8'b10101010;
    B = 8'b11001100;
    OP = 3'b010;

    #10;


    // ------------------------------------
    // 4. NOR
    // ------------------------------------

    A = 8'b10101010;
    B = 8'b01010101;
    OP = 3'b011;

    #10;
	 
    // ------------------------------------
    // 5. NOT A
    // ------------------------------------

    A = 8'b10101010;
    B = 8'b00000000;
    OP = 3'b100;

    #10;


    // ------------------------------------
    // 6. AND
    // ------------------------------------

    A = 8'b11110000;
    B = 8'b10101010;
    OP = 3'b101;

    #10;
	     // ------------------------------------
    // 7. OR
    // ------------------------------------

    A = 8'b11110000;
    B = 8'b10101010;
    OP = 3'b110;

    #10;


    // ------------------------------------
    // 8. B PASS
    // ------------------------------------

    A = 8'b00000000;
    B = 8'b00111100;
    OP = 3'b111;

    #10;
	 
    // ------------------------------------
    // END
    // ------------------------------------

    $finish;

end

endmodule




